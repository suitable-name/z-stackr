//! The z-stackr app: the headless core (everything that does not need the
//! generated Slint `App` type, so it can be unit-tested without a window), the
//! window itself ([`App`], generated from `ui/app.slint`) and the wiring that
//! connects the two ([`gui`]).
//!
//! The desktop binary (`main.rs`) and the browser build (`apps/stacker-web`) are
//! thin entry points over this crate. Everything host-specific (file dialogs,
//! the file system, the per-user config store, the log location) goes through the
//! [`platform`] seam, which each entry point installs.
#![warn(missing_docs)]
#![expect(
    clippy::suboptimal_flops,
    reason = "colour-matrix coefficients; the mul_add form harms readability"
)]

